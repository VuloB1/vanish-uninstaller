const detect = () => {
  try {
    const saved = localStorage.getItem('lang');
    if (saved && M[saved]) return saved;
  } catch {}
  for (const l of navigator.languages?.length ? navigator.languages : [navigator.language]) {
    const code = String(l).toLowerCase().slice(0, 2);
    if (M[code]) return code;
  }
  return 'en';
};

let lang = $state(detect());

export const getLang = () => lang;
export const locale = () => LANGS.find(([c]) => c === lang)[2];
export function setLang(code) {
  if (!M[code]) return;
  lang = code;
  try { localStorage.setItem('lang', code); } catch {}
}

// Per-language font stacks are set from CSS via :root[lang].
$effect.root(() => {
  $effect(() => {
    document.documentElement.lang = lang;
  });
});

export function t(key, p) {
  let s = M[lang][key] ?? M.en[key] ?? M.es[key] ?? key;
  if (p) for (const k in p) s = s.replaceAll(`{${k}}`, p[k]);
  return s;
}

/** Plural-aware lookup: `key.one` / `key.other` (CJK languages define both identically). */
export function tn(key, n, p) {
  const cat = new Intl.PluralRules(locale()).select(n) === 'one' ? 'one' : 'other';
  return t(`${key}.${cat}`, { n, ...p });
}

// Maps the Spanish texts coming from Rust to keys, plus the ones with a variable part.
const STATIC = Object.fromEntries(Object.entries(M.es).filter(([k]) => /^(b|g|e)\./.test(k) && !k.includes('{')).map(([k, v]) => [v, k]));
const PATTERNS = [
  [/^Apunta a un archivo que no existe: (.*)$/s, 'b.pointsTo', (m) => ({ x: m[1] })],
  [/^(.*) — falta (.*)$/s, 'b.missingFor', (m) => ({ a: m[1], b: m[2] })],
  [/^Falta (.*)$/s, 'b.missing', (m) => ({ x: m[1] })],
];

/** Translates a text produced by the Rust side. Unknown texts (and Spanish itself) come back unchanged. */
export function tb(s) {
  if (!s || lang === 'es') return s;
  if (STATIC[s]) return t(STATIC[s]);
  for (const [re, key, params] of PATTERNS) {
    const m = s.match(re);
    if (m) return t(key, params(m));
  }
  // Errors arrive as "<path>: <message>".
  for (const sp in STATIC) if (STATIC[sp].startsWith('e.') && s.endsWith(`: ${sp}`)) return s.slice(0, -sp.length) + t(STATIC[sp]);
  return s;
}
